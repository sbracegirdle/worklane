pub fn plain(s: &str) -> String {
    s.chars()
        .filter(|c| !contains(*c as u32, CONTROL))
        .map(|c| if contains(c as u32, SPACE) { ' ' } else { c })
        .collect()
}
pub fn cell_width(c: char) -> usize {
    if contains(c as u32, COMBINING) {
        0
    } else if contains(c as u32, WIDE) {
        2
    } else {
        1
    }
}
